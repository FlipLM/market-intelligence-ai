/**
 * Retorna todo o repositório de candidatos ordenado pelos mais novos (1 dia, 2 dias, etc.)
 */
export function getNewestPoolCandidates(): RecentCompanyLead[] {
  const result: RecentCompanyLead[] = [];

  // 1. Adiciona os templates artesanais
  POOL_ITEMS.forEach((t, i) => {
    result.push(buildFullLead(t, i));
  });

  // 2. Gera candidatos procedimentais adicionais para garantir mais de 120 empresas novas disponíveis
  let seedIndex = POOL_ITEMS.length;
  for (let d = 1; d <= 45; d++) {
    // 2 empresas por dia de criação
    for (let k = 0; k < 2; k++) {
      seedIndex++;
      const secConf = SETORES_MAP[(seedIndex) % SETORES_MAP.length];
      const nomeBase = secConf.nomes[(seedIndex * 3) % secConf.nomes.length];
      const bairro = BAIRROS_DF[(seedIndex * 5) % BAIRROS_DF.length];
      const socio = NOMES_SOCIOS[(seedIndex * 7) % NOMES_SOCIOS.length];
      
      const numCnpj = 59000000 + seedIndex * 137;
      const cnpjStr = `${String(numCnpj).substring(0, 2)}.${String(numCnpj).substring(2, 5)}.${String(numCnpj).substring(5, 8)}/0001-${String((seedIndex * 17) % 89 + 10)}`;
      const telSuffix = String(1000 + (seedIndex * 23) % 8999);
      const tel = `6198${telSuffix}12`;

      const template: PoolTemplate = {
        razaoSocial: `${nomeBase.toUpperCase()} COMÉRCIO E SERVIÇOS LTDA`,
        nomeFantasia: `${nomeBase} ${bairro}`,
        cnpjBase: cnpjStr,
        diasAtras: d,
        setor: secConf.setor,
        setorRotulo: secConf.rotulo,
        cnae: secConf.cnae,
        cnaeDesc: secConf.cnaeDesc,
        bairro: bairro,
        logradouro: `Avenida Comercial, Bloco ${(seedIndex % 15) + 1}, Loja 0${(seedIndex % 8) + 1}`,
        cep: `71900-${String(100 + (seedIndex % 800))}`,
        porte: 'ME',
        capitalSocial: 40000 + (seedIndex % 10) * 8000,
        socioNome: socio,
        telefone: tel,
        emailDominio: `contato.${nomeBase.toLowerCase().replace(/[^a-z]/g, '')}@gmail.com`,
        dorEspecifica: secConf.dor,
        solucaoSugerida: secConf.solucao,
        setupSugerido: secConf.setup,
        mensalSugerido: secConf.mensal,
        probabilidadeSemSistema: Math.max(82, 99 - Math.floor(d / 4)),
      };

      result.push(buildFullLead(template, seedIndex));
    }
  }

  // Ordena sempre pelos mais recentes primeiro (1 dia, 2 dias, etc.)
  return result.sort((a, b) => a.diasCriacao - b.diasCriacao);
}

/**
 * Busca as 100 empresas mais novas desconsiderando as que já existem na base do usuário
 */
export function fetchTopNewestCompanies(
  existingCnpjs: string[],
  limit: number = 100
): {
  newCompanies: RecentCompanyLead[];
  totalCandidatePool: number;
  skippedCount: number;
} {
  const pool = getNewestPoolCandidates();
  
  // Conjunto de CNPJs limpos (apenas números) já existentes
  const cleanExisting = new Set(existingCnpjs.map(c => c.replace(/\D/g, '')));

  const newCompanies: RecentCompanyLead[] = [];
  let skippedCount = 0;

  for (const lead of pool) {
    const cleanLeadCnpj = lead.cnpj.replace(/\D/g, '');
    if (cleanExisting.has(cleanLeadCnpj)) {
      skippedCount++;
      continue;
    }

    newCompanies.push(lead);
    cleanExisting.add(cleanLeadCnpj); // previne duplicatas internas no pool

    if (newCompanies.length >= limit) {
      break;
    }
  }

  return {
    newCompanies,
    totalCandidatePool: pool.length,
    skippedCount,
  };
}
